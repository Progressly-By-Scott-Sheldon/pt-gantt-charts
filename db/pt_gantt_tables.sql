-- Production schedule Gantt (app 120): tables for the PlanetTogether "Activities" export.
-- Run as WKSP_WKSPDATAPULSE (the Progressly / DATA_PULSE schema) in SQLcl or SQL Workshop.
-- Safe to re-run: every object is created only if it does not exist yet.
--
-- Hierarchy: project > job (job_external_id) > operation (job + operation_external_id)
--            > activity (one per resource).
-- PT_JOBS (the PlanetTogether job publish) is NOT touched here.
-- PT_JOB_PROJECTS.job_external_id matches PT_JOBS.externalid, without a foreign key,
-- because PT_JOBS is replaced on every publish.
--
-- Dates are plant-local wall-clock time (no time zone). PlanetTogether's sentinels
-- 01-01-1800 and 01-01-9000 are stored as NULL. Durations are stored in minutes.
--
-- Rollback: DROP TABLE pt_activities; DROP TABLE pt_job_projects;
--           DROP TABLE pt_resources; DROP TABLE pt_projects;
set define off

create table if not exists pt_projects (
  project_id    number generated by default on null as identity primary key,
  project_name  varchar2(200 char) not null,
  sort_order    number,
  color_code    varchar2(30 char),          -- optional override of the Gantt colour
  created_on    date default sysdate not null,
  constraint pt_projects_name_uk unique (project_name)
);

-- The export has no project column: this is the editable Job External Id -> project mapping.
create table if not exists pt_job_projects (
  job_external_id  varchar2(100 char) primary key,
  project_id       number not null,
  constraint pt_job_projects_proj_fk foreign key (project_id) references pt_projects (project_id)
);
create index if not exists pt_job_projects_proj_ix on pt_job_projects (project_id);

create table if not exists pt_resources (
  resource_id      number generated by default on null as identity primary key,
  resource_name    varchar2(200 char) not null,
  department_name  varchar2(200 char),
  plant_name       varchar2(200 char),
  constraint pt_resources_name_uk unique (plant_name, resource_name)
);

create table if not exists pt_activities (
  activity_id            number generated by default on null as identity primary key,
  resource_id            number not null,
  job_external_id        varchar2(100 char) not null,
  job_name               varchar2(400 char),
  job_product            varchar2(400 char),
  job_quantity           number,
  operation_external_id  varchar2(100 char) not null,
  operation_name         varchar2(400 char),
  production_status      varchar2(50 char),
  scheduled_start        date,
  scheduled_end          date,
  need_date              date,
  is_late                varchar2(1 char) default 'N' not null,
  setup_minutes          number,             -- Calendar Setup
  run_minutes            number,             -- Scheduled Run Time
  activity_quantity      number,
  remaining_quantity     number,
  percent_finished       number,
  bottlenecks            varchar2(400 char), -- Bottlenecked Capabilities
  source_file            varchar2(400 char),
  loaded_on              date default sysdate not null,
  constraint pt_activities_res_fk foreign key (resource_id) references pt_resources (resource_id),
  constraint pt_activities_late_ck check (is_late in ('Y', 'N')),
  constraint pt_activities_uk unique (job_external_id, operation_external_id, resource_id)
);
create index if not exists pt_activities_res_ix on pt_activities (resource_id);
create index if not exists pt_activities_start_ix on pt_activities (scheduled_start);

-- PT_ACTIVITIES_V (what the Gantt reads) is in db/pt_gantt_view.sql: run it after the loads.

-- Rows entered on page 5 (Schedule Data) have no source_file: their late flag follows the
-- dates, the same rule PlanetTogether uses (scheduled end after need date). Exported rows
-- keep the flag from the export.
create or replace trigger pt_activities_biu
  before insert or update on pt_activities
  for each row
begin
  if :new.source_file is null then
    :new.is_late := case when :new.need_date is not null and :new.scheduled_end > :new.need_date then 'Y' else 'N' end;
  end if;
  if :new.scheduled_end < :new.scheduled_start then
    raise_application_error(-20001, 'Scheduled End must be after Scheduled Start.');
  end if;
end;
